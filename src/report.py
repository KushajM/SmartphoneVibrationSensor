"""Write results/SUMMARY.md from the phase outputs (tables, summaries, model)."""
import json

import numpy as np
import pandas as pd

from . import config as C
from . import ml

SUM = C.RESULTS / "summaries"


def _j(name):
    p = SUM / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def _md(df, floatfmt=".3g"):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append("" if np.isnan(v) else format(v, floatfmt))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def write():
    s1, s2, s3 = _j("phase1"), _j("phase2"), _j("phase3_clean")
    cal = json.loads(C.CAL_FILE.read_text())
    ev = cal["evidence"]
    L = []
    w = L.append
    w("# Smartphone vibration classifier - results summary\n")
    w("_Auto-generated by `run_all.py`; every number below is recomputed from `data/raw`._\n")

    w("## Model names used throughout\n")
    w("| name | what it is |\n|---|---|")
    w("| T1_textbook | Threshold rule a first attempt would use: z-axis RMS decides off/on, the biggest FFT peak decides the speed. No ML. |")
    w("| T2_physics | Threshold rule on noise-hardened physics features: harmonic-comb SNR (off/on, constant-false-alarm threshold) + comb fundamental f0 (speed). No ML. |")
    w("| kNN / LR _clean | k-nearest-neighbours / logistic regression trained only on the 80 real recordings; features picked by nested selection. |")
    w("| kNN / LR _aug | Same models trained on the real recordings PLUS noise-augmented copies of them (calibrated noise), so they learn to ignore noise. |")
    w("| HLR_clean / HLR_aug | Two-stage logistic regression: stage A decides 'fan on?', stage B decides 'which speed?' (only for on). **HLR_aug is the final model.** |")
    w("| HLR_aug_known | Final model evaluated when the tested noise type WAS in its training augmentation (normal deployment). All other *_aug results use leave-one-noise-group-out: the tested noise type was never seen in training. |\n")

    w("## 1. Data and acquisition (Week 1)\n")
    if s1:
        w(f"- Device: {s1['device']}, accelerometer {s1['sensor']} (range +-{s1['range']:.1f} m/s^2, "
          f"reported resolution {s1['reported_resolution']}, min delay {s1['min_delay_us']:.0f} us).")
        w(f"- {s1['n_trials']} trials {s1['per_class']}, one session of {s1['session_minutes']:.0f} min, "
          f"round-robin order verified: {s1['round_robin']}.")
        w(f"- Sampling: hardware clock fitted at {s1['fs_fit_mean']:.3f} Hz (range {s1['fs_fit_min']:.3f}-{s1['fs_fit_max']:.3f}); "
          f"timestamp scatter about the fit {s1['ts_resid_us_median']:.2f} us median (max {s1['ts_resid_us_max']:.2f} us) "
          f"vs a 2500 us period; dropped samples: {s1['dropped_total']}; durations {s1['duration_min']:.2f}-{s1['duration_max']:.2f} s.")
        w(f"- Mounting: |g| = {s1['g_norm_mean']:.4f} +- {s1['g_norm_sd']:.4f} m/s^2, in-plane tilt {s1['tilt_inplane_mean']:.2f} deg, "
          f"out-of-plane {s1['tilt_outplane_mean']:.2f} deg; gravity direction drifted {s1['orientation_drift_deg']:.2f} deg over the session.")
        w(f"- Value spacing in the data {s1['value_spacing']:.4f} m/s^2 (quantisation noise ~0.1 x the sensor noise floor).")
        w(f"- Edge check: RMS of the first/last second = {s1['edge_first_median']:.3f} / {s1['edge_last_median']:.3f} x the centre "
          f"(max {s1['edge_max']:.2f}) -> no spin-up or handling transients.")
        w(f"- Flagged trials: {s1['flagged'] or 'none'}.  Figures: `figures/p1_audit.png`.\n")

    w("## 2. Preprocessing choices\n")
    if s1:
        w(f"- **Resampling 400.108 -> 400 Hz with a Kaiser-windowed sinc** (32 taps, beta 8). Linear interpolation was rejected: "
          f"because the two grids slide past each other, its gain at ~100 Hz varies with the fractional offset "
          f"(|1-mu+mu e^-jw|), shrinking the dominant line to {s1['linear_amp_min']:.2f} of its true size and averaging "
          f"{s1['linear_amp_in_window']:.2f} inside the analysis window - this was the 'start-locked decay' seen earlier. "
          f"`figures/p1_resampling.png` (theory curve overlays the measurement).")
    w(f"- Gravity removal: {C.HP_ORDER}th-order Butterworth high-pass at {C.HP_FC} Hz, forward-backward (zero phase), applied to the full "
      f"7 s record before trimming to the central {C.TRIM_S:.0f} s. `figures/p1_gravity_removal.png`.")
    w(f"- Hampel despiker (+-{C.HAMPEL_HALF} samples, {C.HAMPEL_NSIG:.0f} sigma) before resampling; it flags 0 samples in the real data.")
    w(f"- Spectra: mean Welch (Hann, {C.WELCH_NPERSEG} pts, 0.39 Hz) for plots; median Welch ({C.ROB_NPERSEG} pts, 75 % overlap) "
      f"summed over the three axes (orientation-invariant) for the robust features.\n")

    w("## 3. Noise calibration (what 'realistic' means)\n")
    w(f"Measured sensor floor {ev['floor']['nd_ug']:.1f} ug/sqrt(Hz) (datasheet of the same sensor family: 70), Gaussian "
      f"(kurtosis {ev['floor']['kurt']:.2f}), axes uncorrelated (|r| = {ev['floor']['mean_abs_axis_corr']:.2f}); "
      f"the synthetic noise model reproduces it within {abs(ev['floor']['synthetic_sigma_ratio'] - 1):.1%} in sigma and "
      f"{ev['floor']['synthetic_psd_rms_db_err']:.1f} dB rms in spectrum. Fan vibration: broadband SNR {ev['fan']['native_snr_db']:.1f} dB, "
      f"dominant line {ev['fan']['fan_line_rms'] * 1e3:.1f} mm/s^2 RMS, same-day speed scatter {ev['fan']['sameday_sigma_pct']:.2f} %. "
      f"`figures/calib_noise_floor.png`, `figures/calib_fan_and_hum.png`.\n")
    tab = pd.read_csv(C.TAB / "noise_calibration.csv")
    w(_md(tab[["family", "model", "realistic", "evidence_type", "evidence"]]) + "\n")

    w("## 4. Features (Weeks 2-3)\n")
    if s2:
        fq = pd.DataFrame(s2["freq"])[["cls", "fft_fdom_mean", "fft_fdom_sd", "cwt_fdom_mean", "f0_mean", "f0_sd",
                                       "rpm_if_rotation_is_f0", "harmonics_present"]]
        w(_md(fq, ".4g") + "\n")
        w(f"- FFT and CWT dominant frequencies agree within {s2['cwt_vs_fft_max_diff_hz']:.2f} Hz.")
        w(f"- Rotation test (envelope spectrum of the dominant line, `figures/p2_envelope_rotation_test.png`): {s2['envelope']}. "
          f"No modulation or spectral line at f0/3 and a clear 1x line at f0 for speed2/3 -> the shaft turns at f0 "
          f"(~1900-2200 rpm) and the dominant 3f0 line is blade-pass of a 3-blade rotor (confirm by counting blades).")
        rk = pd.read_csv(C.TAB / "feature_ranking.csv").head(10)[["feature", "fisher", "worst_pair_gap_sd", "separable_pairs"]]
        w("\nTop features by Fisher ratio on clean data (`tables/feature_ranking.csv`, `figures/p2_feature_ranking.png`):\n")
        w(_md(rk) + "\n")
        w("Note: the highest clean-data Fisher ratios belong to amplitude features (RMS) that collapse under noise or a "
          "looser mount - discriminability on clean data is not robustness.\n")

    w("## 5. Classification on the real recordings\n")
    cv = pd.read_csv(C.TAB / "clean_cv.csv")
    cv["LORO"] = cv.loro_correct.astype(str) + "/" + cv.loro_n.astype(str)
    cv["95% CI"] = [f"{a:.1%}-{b:.1%}" for a, b in zip(cv.ci95_lo, cv.ci95_hi)]
    cv["5-fold x10"] = [f"{m:.1%} +- {s:.1%}" for m, s in zip(cv.rep5x10_mean, cv.rep5x10_sd)]
    w(_md(cv[["model", "LORO", "95% CI", "5-fold x10"]]) + "\n")
    w("LORO = leave-one-round-out (each fold holds out one full round-robin cycle). Confusion matrices: "
      "`figures/p3_confusion_clean.png`.\n")
    sel = pd.read_csv(C.TAB / "selected_features.csv")
    w("Features chosen inside the folds (nested selection, never sees the test round):\n")
    w(_md(sel[sel.model.isin(["kNN_clean", "LR_clean", "HLR_clean", "kNN_aug", "LR_aug", "HLR_aug"])].groupby("model").head(2)) + "\n")
    if s3:
        m = s3["margins"]
        w(f"- Margins: T2 closest off trial {m['T2_min_snr_margin_off_db']:.2f} dB below its threshold, closest on trial "
          f"{m['T2_min_snr_margin_on_db']:.1f} dB above; closest speed {m['T2_min_f0_margin_hz']:.2f} Hz from a speed boundary. "
          f"Final model: lowest true-class probability {m['HLR_aug_min_true_class_prob']:.2f}, median {m['HLR_aug_median_true_class_prob']:.2f}.")
        w(f"- Final model features: stage A {s3['final_features'][:-1]}, stage B {s3['final_features'][-1:]}; physics rule thresholds "
          f"{s3['t2']}. Decision regions: `figures/p3_final_model_regions.png`.")
        win = pd.DataFrame(s3["window"])
        win["acc"] = [f"{m * 100:.1f} +- {s * 100:.1f}" for m, s in zip(win.rep_mean, win.rep_sd)]
        w("\nAnalysis-window length, 5-fold x10 accuracy mean +- sd (`figures/p3_window_length.png`):\n")
        w(_md(win.pivot(index="window_s", columns="model", values="acc").reset_index()) + "\n")

    rs = C.TAB / "robustness_summary.csv"
    if rs.exists():
        w("## 6. Robustness to noise (test-time corruption)\n")
        w("Worst accuracy inside the calibrated realistic range / first tested level where accuracy drops below 90 % "
          "(`tables/robustness.csv`, `figures/p3_robustness_curves.png`, `figures/p3_robustness_heatmap.png`).\n")
        su = pd.read_csv(rs)
        keep = ["T1_textbook", "T2_physics", "kNN_aug", "HLR_aug", "HLR_aug_known"]
        su = su[su.model.isin(keep)]
        a = su.pivot(index="family", columns="model", values="worst_realistic")[keep] * 100
        s_ = su.pivot(index="family", columns="model", values="worst_realistic_sd")[keep] * 100
        b = su.pivot(index="family", columns="model", values="first_level_below_90")[keep]
        t = pd.DataFrame({m: [("n/a" if np.isnan(a.loc[f, m]) else f"{a.loc[f, m]:.0f}+-{s_.loc[f, m]:.0f} %")
                              + f" / {b.loc[f, m]}" for f in a.index] for m in keep}, index=a.index).reset_index()
        w(_md(t) + "\n")
        ab = C.TAB / "ablation.csv"
        if ab.exists():
            d = pd.read_csv(ab)
            d["acc"] = (d.acc * 100).round(1)
            w("Ablation (`figures/p3_ablation.png`):\n")
            rows = []
            for (comp, test), g in d.groupby(["component", "test"], sort=False):
                r = dict(component=comp, test=test)
                for m in ("T2_physics", "HLR_clean"):
                    gm = g[g.model == m]
                    r[f"{m} full"] = gm[gm.variant == "full front-end"].acc.iloc[0]
                    r[f"{m} without"] = gm[gm.variant != "full front-end"].acc.iloc[0]
                rows.append(r)
            w(_md(pd.DataFrame(rows), ".1f") + "\n")

    w("## 7. Limits - what these results do not show\n")
    w(f"- One fan, one phone, one mount, one evening. Day-to-day supply-voltage changes (+-6 % statutory) move the fan speed by "
      f"+-{ev['speed']['day_pct_lo']:.1f}-{ev['speed']['day_pct_hi']:.1f} %, but the speed classes are only ~7 % apart and every classifier "
      f"fails beyond ~3 %: this is a change of the measured quantity, not noise. Re-calibrating thresholds with one recording per "
      f"speed at deployment, or measuring the mains voltage, is the fix.")
    w("- A foreign machine whose tone lands on a fan line (e.g. a 2-pole compressor at ~2x48 Hz on speed1's 96 Hz line) is "
      "physically indistinguishable from the fan when the other harmonics are buried - its amplitude is uncalibrated.")
    w("- Much worse sensors (>= ~300 ug/sqrt(Hz), 12-bit ADCs) or apps capped at 200 Hz lose the dominant line.")
    w("- Noise models are calibrated, not measured in situ: footstep/knock amplitudes come from literature anchors, "
      "re-taping effects (orientation/gain) are assumptions; all are flagged in section 3.")
    (C.RESULTS / "SUMMARY.md").write_text("\n".join(L), encoding="utf-8")
    return C.RESULTS / "SUMMARY.md"
